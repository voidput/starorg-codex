#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md: license texts of every third-party Rust crate (cargo-about,
# about.toml) and npm package (scripts/notices/npm.mjs) that ships in the app or the CLI.
# Run after any Cargo.lock or app/package-lock.json change and commit the result.
#   scripts/gen-notices.sh          write the file
#   scripts/gen-notices.sh --check  exit 1 if the committed file is stale (CI)
# Needs: cargo-about 0.9 (`cargo install cargo-about --locked --features cli`), node, and
# app/node_modules (`npm ci` in app/).
set -euo pipefail
cd "$(dirname "$0")/.."

out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cargo about generate --workspace --fail --locked -c about.toml scripts/notices/rust.hbs -o "$tmp/rust.md"
node scripts/notices/npm.mjs > "$tmp/npm.md"

{
  cat <<'HEAD'
# Third-party notices

StarOrg Codex (the app and the `starorg-codex` CLI) is MIT licensed (see LICENSE). It includes
the third-party software listed below, each under its own license. This file is generated by
`scripts/gen-notices.sh`; do not edit it by hand.

HEAD
  cat "$tmp/rust.md"
  echo
  cat "$tmp/npm.md"
} | sed -e 's/[[:space:]]*$//' | cat -s > "$tmp/$out"

if [ "${1:-}" = --check ]; then
  if ! diff -q "$out" "$tmp/$out" >/dev/null; then
    diff -u "$out" "$tmp/$out" | head -40 || true
    echo "::error::$out is stale: run scripts/gen-notices.sh and commit the result" >&2
    exit 1
  fi
  echo "$out is up to date"
else
  cp "$tmp/$out" "$out"
  echo "wrote $out ($(wc -c < "$out") bytes)"
fi
